def normaliser_nom_avec_arrondissement(nom, code_dept=None):

    nom_norm = nom.upper().strip()

    # Pattern pour détecter les arrondissements avec "ARRONDISSEMENT"
    # Ex: "PARIS 13E ARRONDISSEMENT" ou "PARIS 1ER ARRONDISSEMENT"
    pattern_long = r'^(PARIS|LYON|MARSEILLE)\s+(\d+)(?:ER|E|EME)?\s+ARRONDISSEMENT'
    match_long = re.match(pattern_long, nom_norm)

    if match_long:
        ville = match_long.group(1)
        numero = match_long.group(2).zfill(2)
        return f"{ville} {numero}"

    # Pattern pour détecter le format court avec suffixe
    # Ex: "PARIS 13", "LYON 2EME", "MARSEILLE 1ER"
    pattern_court = r'^(PARIS|LYON|MARSEILLE)\s+(\d+)(?:ER|E|EME)?$'
    match_court = re.match(pattern_court, nom_norm)

    if match_court:
        ville = match_court.group(1)
        numero = match_court.group(2).zfill(2)
        return f"{ville} {numero}"

    return normaliser_nom(nom)


