def nettoyage(df):
    df = df[df['Nature mutation'] == 'Vente']
    df = df[['Date mutation', 'Valeur fonciere', 'Code postal', 'Commune', 'Code departement', 'Code type local', 'Surface reelle bati', 'Surface terrain']]
    df = df.dropna(subset=['Valeur fonciere', 'Code postal', 'Code type local', 'Surface reelle bati']).reset_index(drop=True)
    df = df.drop_duplicates()
    df = df[df['Code type local'].isin([1, 2])]

    df['Date mutation'] = pd.to_datetime(df['Date mutation'], format='%d/%m/%Y', errors='coerce')
    df['Année'] = df['Date mutation'].dt.year
    df['Valeur fonciere'] = df['Valeur fonciere'].astype(str).str.replace(',', '.').str.replace(r'\s+', '', regex=True).astype(float).round().astype(int)
    df['Surface reelle bati'] = df['Surface reelle bati'].astype(int)
    df['Surface terrain'] = df['Surface terrain'].fillna(0).astype(int)
    df['Code type local'] = df['Code type local'].astype(int)
    df.drop(columns=['Date mutation'], inplace=True)

    # Filtres prix et surface minimum
    df = df[(df['Valeur fonciere'] >= 30000) & (df['Surface reelle bati'] >= 15)]

    numeric_df = df[['Valeur fonciere', 'Surface reelle bati', 'Surface terrain']]

    iso_forest = IsolationForest(contamination=0.15, random_state=42)
    predictions = iso_forest.fit_predict(numeric_df)

    df['anomaly'] = predictions
    df_clean = df[predictions == 1]
    df_clean = df_clean.drop(columns=['anomaly'])
    df_clean = df_clean.reset_index(drop=True)

    return df_clean

