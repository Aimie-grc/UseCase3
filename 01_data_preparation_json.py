def normaliser_nom(nom):
    if pd.isna(nom):
        return nom

    nom_normalise = str(nom).upper() # 1. Passage en majuscules
    nom_normalise = nom_normalise.replace('-', ' ').replace("'", ' ')
    nom_normalise = re.sub(r'\bST\s', 'SAINT ', nom_normalise)
    nom_normalise = re.sub(r'\bSTe\s', 'SAINTE ', nom_normalise)
    nom_normalise = unidecode.unidecode(nom_normalise) # 2. Suppression des accents
    nom_normalise = re.sub(r'\([^)]*\)', '', nom_normalise) # 3. Suppression des parenthèses

    match_chiffre = re.search(r'\d', nom_normalise)
    if match_chiffre:
        index_chiffre = match_chiffre.start()
        nom_normalise = nom_normalise[:index_chiffre]

    nom_normalise = ' '.join(nom_normalise.split()) # Supprimer les espaces multiples

    return nom_normalise

