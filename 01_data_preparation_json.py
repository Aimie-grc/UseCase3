def download_all_dvf_files(output_dir="dvf_data", force_redownload=False):
    """
    Télécharge et décompresse tous les fichiers DVF disponibles

    Args:
        output_dir: dossier de destination
        force_redownload: re-télécharger même si les fichiers existent

    Returns:
        Dictionnaire {année: filepath}
    """
    Path(output_dir).mkdir(exist_ok=True)

    api_url = f"https://www.data.gouv.fr/api/1/datasets/{DATASET_ID}/"
    response = requests.get(api_url)

    if response.status_code != 200:
        print(f"Erreur API: {response.status_code}")
        return {}

    dataset = response.json()
    downloaded_files = {}

    print(f"Dataset: {dataset['title']}\n")

    for resource in dataset['resources']:
        title = resource.get('title', '')
        url = resource.get('url', '')
        format_type = resource.get('format', '').lower()

        # Extraire l'année
        year_match = re.search(r'20\d{2}', title)
        if not year_match:
            continue

        year = year_match.group()

        # Gérer les fichiers TXT et ZIP
        if 'txt' in format_type or 'zip' in format_type:
            filename = f"dvf_{year}.txt"
            filepath = os.path.join(output_dir, filename)

            # Vérifier si déjà téléchargé
            if os.path.exists(filepath) and not force_redownload:
                file_size = os.path.getsize(filepath) / (1024 * 1024)
                if file_size > 1:  # Au moins 1 MB
                    print(f"⏭  {filename} existe déjà ({file_size:.2f} MB)")
                    downloaded_files[year] = filepath
                    continue

            try:
                print(f"Téléchargement: {title}")
                file_response = requests.get(url, stream=True, timeout=180)

                if file_response.status_code != 200:
                    print(f"  ✗ Erreur HTTP {file_response.status_code}\n")
                    continue

                # Sauvegarder temporairement
                temp_file = os.path.join(output_dir, f"temp_{year}")
                with open(temp_file, 'wb') as f:
                    for chunk in file_response.iter_content(chunk_size=8192):
                        f.write(chunk)

                # Si c'est un ZIP, décompresser
                if zipfile.is_zipfile(temp_file):
                    print(f"  Décompression du ZIP...")
                    with zipfile.ZipFile(temp_file, 'r') as zip_ref:
                        txt_files = [f for f in zip_ref.namelist() if f.endswith('.txt')]
                        if txt_files:
                            zip_ref.extract(txt_files[0], output_dir)
                            extracted = os.path.join(output_dir, txt_files[0])
                            os.rename(extracted, filepath)
                    os.remove(temp_file)
                else:
                    os.rename(temp_file, filepath)

                file_size = os.path.getsize(filepath) / (1024 * 1024)
                print(f"  ✓ {filename} prêt ({file_size:.2f} MB)\n")
                downloaded_files[year] = filepath

            except Exception as e:
                print(f"  ✗ Erreur: {e}\n")
                if os.path.exists(temp_file):
                    os.remove(temp_file)

    print(f"{'='*60}")
    print(f"Résumé: {len(downloaded_files)} fichiers téléchargés")
    print(f"Années: {sorted(downloaded_files.keys(), reverse=True)}")
    print(f"{'='*60}\n")

    return downloaded_files


def load_dvf_by_chunks(filepath, chunksize=50000):
    """
    Charge un fichier DVF par morceaux

    Args:
        filepath: chemin vers le fichier
        chunksize: nombre de lignes par chunk

    Returns:
        DataFrame complet
    """
    print(f"Chargement de {filepath}...")

    chunks = []
    total_rows = 0

    try:
        for i, chunk in enumerate(pd.read_csv(
            filepath,
            sep='|',
            encoding='latin-1',
            chunksize=chunksize,
            on_bad_lines='skip',
            engine='python'
        )):
            chunks.append(chunk)
            total_rows += len(chunk)
            if (i + 1) % 10 == 0:
                print(f"  Chunk {i+1}: {total_rows:,} lignes chargées...")

        df = pd.concat(chunks, ignore_index=True)
        df.columns = df.columns.str.strip()

        print(f"✓ {len(df):,} lignes chargées au total")
        print(f"✓ {len(df.columns)} colonnes\n")

        return df

    except Exception as e:
        print(f"✗ Erreur: {e}\n")
        return None


def run_dvf_pipeline(
    years=None,
    output_dir="dvf_data",
    force_redownload=False
):
    """
    Pipeline complet DVF : téléchargement + chargement complet

    Args:
        years: liste d'années à traiter, ex: ['2023', '2024']
               None = toutes les années disponibles
        output_dir: dossier de destination
        force_redownload: re-télécharger même si fichiers existants

    Returns:
        Dictionnaire {année: DataFrame}
    """

    # ── 1. Téléchargement ─────────────────────────────────────────
    print("=== ÉTAPE 1 : Téléchargement ===")
    downloaded = download_all_dvf_files(
        output_dir=output_dir,
        force_redownload=force_redownload
    )

    if not downloaded:
        print("Aucun fichier téléchargé. Abandon.")
        return {}

    # Filtrer sur les années demandées
    if years is not None:
        years = [str(y) for y in years]
        downloaded = {y: p for y, p in downloaded.items() if y in years}
        missing = set(years) - set(downloaded.keys())
        if missing:
            print(f"⚠ Années introuvables : {sorted(missing)}")

    # ── 2. Chargement complet ─────────────────────────────────────
    print("\n=== ÉTAPE 2 : Chargement ===")
    dfs = {}

    for year, filepath in sorted(downloaded.items(), reverse=True):
        print(f"\n── Année {year} ──")
        df = load_dvf_by_chunks(filepath)

        if df is not None and len(df) > 0:
            dfs[year] = df

    if not dfs:
        print("Aucune donnée chargée. Abandon.")
        return {}

    # ── 3. Injection dans le namespace global ─────────────────────
    for year, df in dfs.items():
        globals()[f"df_{year}"] = df

    print(f"\n{'='*50}")
    print(f"✓ Pipeline terminé — {len(dfs)} année(s) chargée(s) : "
          f"{sorted(dfs.keys(), reverse=True)}")
    print(f"✓ Variables créées : "
          f"{['df_' + y for y in sorted(dfs.keys(), reverse=True)]}")

    return dfs

